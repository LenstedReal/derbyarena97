#if UNITY_EDITOR
using System.IO;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.Rendering.Universal;

namespace DerbyArena.EditorTools
{
    /// <summary>
    /// Recreates and enforces the project's URP + Android settings.
    /// This is intentionally idempotent so a clean Cloud Build checkout can
    /// repair missing ProjectSettings/GraphicsSettings/QualitySettings data.
    /// </summary>
    [InitializeOnLoad]
    public static class UrpAndPlayerSetup
    {
        const string SettingsFolder = "Assets/DerbyArena/Settings";
        const string RendererPath = SettingsFolder + "/BlackoutRenderer.asset";
        const string PipelinePath = SettingsFolder + "/BlackoutURP.asset";
        const string ScenePath = "Assets/DerbyArena/Scenes/BlackoutSpillway.unity";

        static UrpAndPlayerSetup()
        {
            EditorApplication.delayCall += TrySetupFromEditor;
        }

        static void TrySetupFromEditor()
        {
            if (EditorApplication.isCompiling || EditorApplication.isUpdating)
                return;

            try
            {
                ApplyBuildSettings();
            }
            catch (System.Exception ex)
            {
                Debug.LogError("DERBY editor setup failed: " + ex);
            }
        }

        [MenuItem("Derby/Repair Project And Android Settings")]
        public static void Setup()
        {
            ApplyBuildSettings();
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);
        }

        public static void ApplyBuildSettings()
        {
            if (!File.Exists(ScenePath))
                throw new BuildFailedException("DERBY: startup scene is missing: " + ScenePath);

            Directory.CreateDirectory(SettingsFolder);
            AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);

            var renderer = AssetDatabase.LoadAssetAtPath<UniversalRendererData>(RendererPath);
            if (renderer == null)
            {
                renderer = ScriptableObject.CreateInstance<UniversalRendererData>();
                renderer.name = "BlackoutRenderer";
                AssetDatabase.CreateAsset(renderer, RendererPath);
            }

            var pipeline = AssetDatabase.LoadAssetAtPath<UniversalRenderPipelineAsset>(PipelinePath);
            if (pipeline != null)
            {
                var existing = new SerializedObject(pipeline).FindProperty("m_RendererDataList");
                if (existing == null || existing.arraySize == 0)
                {
                    // Repair the incomplete asset generated by the previous
                    // ScriptableObject.CreateInstance-only setup.
                    AssetDatabase.DeleteAsset(PipelinePath);
                    pipeline = null;
                }
            }

            if (pipeline == null)
            {
                // Use URP's factory. CreateInstance<UniversalRenderPipelineAsset>()
                // leaves required renderer/resource defaults uninitialized.
                pipeline = UniversalRenderPipelineAsset.Create(renderer);
                pipeline.name = "BlackoutURP";
                AssetDatabase.CreateAsset(pipeline, PipelinePath);
            }

            // Rebind the renderer explicitly in case an earlier generated asset
            // exists but has an empty or stale renderer reference.
            var serializedPipeline = new SerializedObject(pipeline);
            var rendererList = serializedPipeline.FindProperty("m_RendererDataList");
            if (rendererList == null)
                throw new BuildFailedException("DERBY: URP asset has no renderer data list.");

            if (rendererList.arraySize != 1)
                rendererList.arraySize = 1;

            var rendererElement = rendererList.GetArrayElementAtIndex(0);
            if (rendererElement.objectReferenceValue != renderer)
                rendererElement.objectReferenceValue = renderer;
            serializedPipeline.ApplyModifiedPropertiesWithoutUndo();

            GraphicsSettings.defaultRenderPipeline = pipeline;

            // A quality-level override takes precedence over Graphics settings.
            // Assign the same pipeline at every quality level to prevent a
            // device/build profile from silently falling back to Built-in.
            string[] qualityNames = QualitySettings.names;
            int previousQuality = QualitySettings.GetQualityLevel();
            if (qualityNames != null && qualityNames.Length > 0)
            {
                for (int i = 0; i < qualityNames.Length; i++)
                {
                    QualitySettings.SetQualityLevel(i, false);
                    QualitySettings.renderPipeline = pipeline;
                }
                QualitySettings.SetQualityLevel(
                    Mathf.Clamp(previousQuality, 0, qualityNames.Length - 1), false);
            }
            else
            {
                QualitySettings.renderPipeline = pipeline;
            }

            PlayerSettings.companyName = "LenstedReal";
            PlayerSettings.productName = "DERBY ARENA";
            PlayerSettings.bundleVersion = "1.0.8";
            PlayerSettings.SetApplicationIdentifier(
                NamedBuildTarget.Android, "com.lenstedreal.derbyarena");
            PlayerSettings.Android.bundleVersionCode = 108;
            PlayerSettings.defaultInterfaceOrientation = UIOrientation.LandscapeLeft;
            PlayerSettings.allowedAutorotateToPortrait = false;
            PlayerSettings.allowedAutorotateToPortraitUpsideDown = false;
            PlayerSettings.allowedAutorotateToLandscapeLeft = true;
            PlayerSettings.allowedAutorotateToLandscapeRight = true;
            PlayerSettings.SetScriptingBackend(
                NamedBuildTarget.Android, ScriptingImplementation.IL2CPP);
            PlayerSettings.Android.targetArchitectures = AndroidArchitecture.ARM64;
            PlayerSettings.Android.minSdkVersion = AndroidSdkVersions.AndroidApiLevel25;
            PlayerSettings.colorSpace = ColorSpace.Linear;
            PlayerSettings.Android.renderOutsideSafeArea = true;

            EditorBuildSettings.scenes = new[]
            {
                new EditorBuildSettingsScene(ScenePath, true)
            };

            EditorUtility.SetDirty(renderer);
            EditorUtility.SetDirty(pipeline);
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();

            if (GraphicsSettings.defaultRenderPipeline != pipeline)
                throw new BuildFailedException("DERBY: URP pipeline was not assigned.");
            if (rendererList.arraySize == 0 ||
                rendererList.GetArrayElementAtIndex(0).objectReferenceValue != renderer)
                throw new BuildFailedException("DERBY: URP renderer reference is invalid.");

            Debug.Log(
                "DERBY BUILD SETTINGS APPLIED: URP / DERBY ARENA / 1.0.8 / 108 / ARM64");
        }
    }

    public sealed class DerbyBuildSettingsEnforcer : IPreprocessBuildWithReport
    {
        public int callbackOrder => -1000;

        public void OnPreprocessBuild(BuildReport report)
        {
            UrpAndPlayerSetup.ApplyBuildSettings();
        }
    }

    public static class BatchValidate
    {
        public static void Run()
        {
            UrpAndPlayerSetup.ApplyBuildSettings();
            var scene = UnityEditor.SceneManagement.EditorSceneManager.OpenScene("Assets/DerbyArena/Scenes/BlackoutSpillway.unity");
            var boot = Object.FindAnyObjectByType<DerbyArena.Core.DerbyBootstrap>();
            EditorApplication.Exit(boot == null || string.IsNullOrEmpty(scene.path) ? 2 : 0);
        }
    }
}
#endif
